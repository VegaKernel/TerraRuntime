    // Independent official LegacyDungeonHall.GenerateHall output, all normalized fields, x-major.
    // TerrariaServer 1.4.5.8 Linux SHA256:
    // 4B87890AC53D40F61DB5F928693A379ACF4CCBD8ED3B47EB32FB096F145DF034.
    public static IEnumerable<object[]> OfficialHalls()
    {
        foreach (string row in Reference.Split('\n', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries))
        {
            string[] fields = row.Split('|');
            yield return [int.Parse(fields[0], CultureInfo.InvariantCulture),
                int.Parse(fields[1], CultureInfo.InvariantCulture), int.Parse(fields[2], CultureInfo.InvariantCulture), fields[3], fields[4], fields[5]];
        }
    }

    [Theory]
    [MemberData(nameof(OfficialHalls))]
    public void Hall_matches_official_full_cells_endpoint_and_direction(int fixture, int palette, int seed,
        string hash, string end, string direction)
    {
        WorldTileStore tiles = Fixture(fixture);
        DungeonPoint1458 origin = Origin(fixture);
        ushort brick = palette == 0 ? (ushort)41 : palette == 1 ? (ushort)43 : (ushort)44;
        ushort wall = (ushort)(7 + palette), crackedBrick = (ushort)(481 + palette);
        if (fixture == 13)
            DungeonLegacyRoom1458.Generate(tiles, brick, wall, origin, 42, false, TestContext.Current.CancellationToken);
        DungeonPoint1458 previous = fixture == 11 ? new(1, 0) : fixture == 12 ? new(0, -1) : default;
        var result = new DungeonLegacyHall1458(tiles, brick, crackedBrick, wall, fixture == 14 ? 440 : 200, 600,
            TestContext.Current.CancellationToken).Generate(origin, previous, seed);
        Assert.Equal(hash, Hash(tiles));
        Assert.Equal(Point(end), result.Cursor);
        Assert.Equal(Point(direction), result.Direction);
        Assert.Equal(result.Cursor, result.Component.End);
        Assert.Equal(origin, result.Component.Start);
        Assert.Equal(DungeonComponentKind1458.Hall, result.Component.Kind);
        Assert.Equal(seed, result.Component.RandomSeed);
    }

    [Fact]
    public void Cancelled_hall_does_not_mutate_candidate()
    {
        WorldTileStore tiles = Fixture(0);
        string before = Hash(tiles);
        Assert.Throws<OperationCanceledException>(() =>
            new DungeonLegacyHall1458(tiles, 41, 481, 7, 200, 600, new CancellationToken(true))
                .Generate(Origin(0), default, 42));
        Assert.Equal(before, Hash(tiles));
    }

    [Fact]
    public void Unsupported_palette_does_not_mutate_candidate()
    {
        WorldTileStore tiles = Fixture(0);
        string before = Hash(tiles);
        Assert.Throws<InvalidOperationException>(() =>
            new DungeonLegacyHall1458(tiles, 41, 482, 7, 200, 600, TestContext.Current.CancellationToken)
                .Generate(Origin(0), default, 42));
        Assert.Equal(before, Hash(tiles));
    }

    private static DungeonPoint1458 Origin(int fixture) => fixture switch
    {
        3 => new(250, 150), 4 => new(250, 510), 5 => new(150, 450), 6 => new(850, 450),
        7 => new(400, 450), 8 => new(600, 450), 9 => new(500, 450), _ => new(250, 450)
    };

    private static DungeonPoint1458 Point(string text)
    {
        string[] values = text.Split(',');
        return new((int)double.Parse(values[0], CultureInfo.InvariantCulture),
            (int)double.Parse(values[1], CultureInfo.InvariantCulture));
    }

    private static WorldTileStore Fixture(int fixture)
    {
        var tiles = new WorldTileStore(new WorldDimensions(1000, 800));
        for (int x = 0; x < 1000; x++)
        for (int y = 0; y < 800; y++)
        {
            int variant = (x / 5 + y / 7) % 3;
            WorldTileFlags flags = WorldTileFlags.WireRed;
            if (fixture != 2 || variant != 2) flags |= WorldTileFlags.Active;
            if (fixture == 10) flags |= WorldTileFlagMasks.Actuation | WorldTileFlagMasks.Visibility | WorldTileFlagMasks.Fullbright;
            tiles.Set(x, y, new WorldTile
            {
                Type = fixture == 2 ? (ushort)(variant == 0 ? 481 : variant == 1 ? 677 : 0) : (ushort)1,
                Wall = fixture == 1 ? (ushort)(variant == 0 ? 7 : variant == 1 ? 40 : 8) :
                    fixture == 2 ? (ushort)7 : fixture == 10 ? (ushort)350 : (ushort)40,
                FrameX = 18, FrameY = 36, TileColor = 3, WallColor = 4,
                LiquidAmount = 17, LiquidKind = WorldLiquidKind.Lava,
                Shape = fixture == 10 ? (byte)3 : (byte)0, Flags = flags
            });
        }
        return tiles;
    }

    private static string Hash(WorldTileStore tiles)
    {
        var cells = new WorldTile[1000 * 800];
        for (int x = 0; x < 1000; x++)
        for (int y = 0; y < 800; y++)
            cells[x * 800 + y] = tiles.Get(x, y);
        return Convert.ToHexString(SHA256.HashData(MemoryMarshal.AsBytes(cells.AsSpan())));
    }

