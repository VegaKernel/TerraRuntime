    public void Grown_tree_matches_official_final_cells_and_random(int otherSupportSide, int seed, string hash, int next)
    {
        var store = new WorldTileStore(new WorldDimensions(100,100));
        for (int x = 49; x <= 51; x++)
            store.Tiles[store.GetUncheckedIndex(x,70)] = new WorldTile
            {
                Type = (ushort)(otherSupportSide != 0 && x == 50 + otherSupportSide ? 2 : 633),
                TileColor = 9,
                Flags = WorldTileFlags.Active | WorldTileFlags.InvisibleBlock | WorldTileFlags.FullbrightBlock
            };
        var random = new RandomAdapter(seed);
        Assert.True(AshTreeGrower1458.TryGrow(store,50,70,random));
        var cells = new WorldTile[10000];
        for (int x = 0; x < 100; x++)
        for (int y = 0; y < 100; y++) cells[x*100+y] = store.Get(x,y);
        Assert.Equal(hash, Convert.ToHexString(SHA256.HashData(MemoryMarshal.AsBytes(cells.AsSpan()))));
        Assert.Equal(next, random.Next());
    }

    private sealed class RandomAdapter(int seed) : IWorldGenerationVanillaRandom
    {
        private readonly VanillaUnifiedRandom1458 random = new(seed);
        public int Next() => random.Next();
        public int Next(int max) => random.Next(max);
        public int Next(int min, int max) => random.Next(min,max);
        public double NextDouble() => random.NextDouble();
        public void NextBytes(byte[] bytes) => random.NextBytes(bytes);
    }
