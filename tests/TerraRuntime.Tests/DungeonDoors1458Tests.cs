    // Original TerrariaServer 1.4.5.8 executable SHA256
    // 4B87890AC53D40F61DB5F928693A379ACF4CCBD8ED3B47EB32FB096F145DF034.
    // Whole normalized tile arrays and the next shared random value; fixture inputs contain no output logic.
    public static IEnumerable<object[]> Cases => Reference.Split('\n', StringSplitOptions.RemoveEmptyEntries)
        .Select(line => line.Trim().Split('|')).Select(p => new object[]
        { int.Parse(p[0]), int.Parse(p[1]), int.Parse(p[2]), int.Parse(p[3]), p[4], int.Parse(p[5]) });

    [Theory, MemberData(nameof(Cases))]
    public void Search_masonry_frames_clearance_and_rng_match_official(int fixture, int palette, int direction, int seed, string expected, int next)
    {
        var tiles = DungeonDoorFixture1458.Tiles(fixture, palette);
        var candidate = DungeonDoorFixture1458.Candidate(fixture, direction);
        var random = new RandomAdapter(seed);
        new DungeonDoors1458(tiles, random, CancellationToken.None).Place(fixture == 10 ? [candidate, candidate] : [candidate],
            new ushort[] { 41, 43, 44 }[palette], (ushort)(7 + palette), palette);
        Assert.Equal(expected, Hash(tiles));
        Assert.Equal(next, random.Next());
    }

    [Fact]
    public void Missing_floor_fails_closed_without_out_of_bounds_or_mutation()
    {
        var tiles = DungeonDoorFixture1458.Tiles(8, 0);
        string before = Hash(tiles);
        Assert.Equal(0, new DungeonDoors1458(tiles, new RandomAdapter(42), CancellationToken.None)
            .Place([DungeonDoorFixture1458.Candidate(8, 0)], 41, 7, 0));
        Assert.Equal(before, Hash(tiles));
    }

    [Fact]
    public void Cancellation_and_unsupported_palette_do_not_mutate()
    {
        var tiles = DungeonDoorFixture1458.Tiles(0, 0);
        string before = Hash(tiles);
        var candidates = new[] { DungeonDoorFixture1458.Candidate(0, 0) };
        Assert.Throws<OperationCanceledException>(() => new DungeonDoors1458(tiles, new RandomAdapter(42), new CancellationToken(true)).Place(candidates, 41, 7, 0));
        Assert.Throws<InvalidOperationException>(() => new DungeonDoors1458(tiles, new RandomAdapter(42), CancellationToken.None).Place(candidates, 41, 8, 0));
        Assert.Equal(before, Hash(tiles));
    }

