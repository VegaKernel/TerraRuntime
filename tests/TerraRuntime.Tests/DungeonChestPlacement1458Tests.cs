    // Original 1.4.5.8 AddBuriedChest, same executable hash as DungeonChestLoot1458Tests.
    public static IEnumerable<object[]> Cases() => Reference.Split('\n', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries)
        .Select(row => new object[] { row });

    [Theory]
    [MemberData(nameof(Cases))]
    public void Burial_geometry_metadata_inventory_and_rng_match_original(string reference)
    {
        string[] f = reference.Split('|');
        var workspace = DungeonChestPlacementFixture1458.Create(Int(f[1]));
        var random = new RandomAdapter(1458);
        bool success = new DungeonChests1458(workspace, random, DungeonChestLoot1458Tests.Bootstrap(), 100, 200,
            TestContext.Current.CancellationToken).TryPlace(200, 300, (ushort)Int(f[3]), Int(f[4]), Int(f[2]));
        Assert.Equal(bool.Parse(f[5]), success);
        Assert.Equal(f[6], Hash(workspace.TileStore));
        Assert.Equal(Int(f[8]), random.Next());
        var chests = workspace.CaptureGeneratedChests();
        if (!success) { Assert.Empty(chests); return; }
        var chest = Assert.Single(chests);
        Assert.Equal(199, chest.X); Assert.Equal(398, chest.Y);
        Assert.Equal(40, chest.Items.Length);
        Assert.Equal(f[7], string.Join(';', chest.Items.Where(v => !v.IsEmpty).Select(v => $"{v.ItemType},{v.Stack},{v.Prefix}")));
    }

    [Fact]
    public void Cancellation_precedes_any_chest_or_rng_mutation()
    {
        var workspace = DungeonChestPlacementFixture1458.Create(0);
        string before = Hash(workspace.TileStore);
        var random = new RandomAdapter(1458);
        Assert.Throws<OperationCanceledException>(() => new DungeonChests1458(workspace, random,
            DungeonChestLoot1458Tests.Bootstrap(), 100, 200, new CancellationToken(true)).TryPlace(200, 300, 21, 2, 155));
        Assert.Equal(before, Hash(workspace.TileStore)); Assert.Equal(0, workspace.GeneratedChestCount);
        Assert.Equal(906992634, random.Next());
    }

