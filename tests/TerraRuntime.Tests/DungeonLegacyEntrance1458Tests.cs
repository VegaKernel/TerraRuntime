    [Theory]
    [MemberData(nameof(OfficialBuildings))]
    public void Production_entrance_renderer_matches_official_building_and_metadata(string reference)
    {
        string[] f = reference.Split('|');
        int fixture = Int(f[0]), palette = Int(f[1]), seed = Int(f[2]);
        bool right = bool.Parse(f[3]);
        ushort brick = palette == 0 ? (ushort)41 : palette == 1 ? (ushort)43 : (ushort)44;
        ushort wall = (ushort)(7 + palette);
        WorldTileStore tiles = Fixture(fixture, wall);
        var random = new RandomAdapter(6789);
        var renderer = new DungeonGraphGenerator1458.Renderer(tiles, brick, (ushort)(481 + palette), wall,
            150.25, 220, 400, 1, 998, fixture == 3 ? 29 : 25, fixture == 3 ? 24 : 20,
            fixture == 3 ? 49 : 35, fixture == 3 ? 14 : 10, TestContext.Current.CancellationToken);
        var origin = new DungeonPoint1458(right ? 750 : 250, fixture == 1 ? 130 : 150);
        DungeonEntranceResult1458 result = renderer.RenderEntrance(origin, DungeonEntranceKind1458.Legacy, seed, random, !right);
        DungeonSamplingBoundsReference1458.AssertMatches($"Building|{fixture}|{palette}|{seed}|{right}", tiles.Dimensions,
            new(500, 450), [result.Component], result.GenerationTopOverride);
        Assert.Equal(f[4], Hash(tiles));
        Assert.Equal(Int(f[5]), random.Next());
        Assert.Equal(Point(f[6]), result.OldManSpawn);
        int[] b = f[7].Split(',').Select(Int).ToArray();
        Assert.Equal(new DungeonBounds1458(b[0], b[1], b[2] - 1, b[3] - 1), result.Component.Bounds);
        Assert.Equal(f[8].Length == 0 ? (DungeonPoint1458?)null : Point(f[8]), result.Platform);
        Assert.Equal(origin, result.Component.Start);
        Assert.Equal(result.OldManSpawn, result.Component.End);
        Assert.Equal(DungeonComponentKind1458.Entrance, result.Component.Kind);
        Assert.Equal(seed, result.Component.RandomSeed);
    }

    [Theory]
    [InlineData(0)]
    [InlineData(1)]
    [InlineData(2)]
    [InlineData(3)]
    public void Invalid_or_cancelled_entrance_preserves_tiles_and_shared_random(int rejection)
    {
        WorldTileStore tiles = Fixture(0, 7);
        string before = Hash(tiles);
        var random = new RandomAdapter(6789);
        var renderer = new DungeonGraphGenerator1458.Renderer(tiles, 41, 481, rejection == 1 ? (ushort)8 : (ushort)7,
            150.25, 220, 400, 1, 998, 25, 20, 35, 10, new CancellationToken(rejection == 0));
        var origin = new DungeonPoint1458(rejection == 2 ? 1 : 250, 150);
        var kind = rejection == 3 ? (DungeonEntranceKind1458)byte.MaxValue : DungeonEntranceKind1458.Legacy;
        if (rejection == 0)
            Assert.Throws<OperationCanceledException>(() => renderer.RenderEntrance(origin, kind, 42, random, true));
        else
            Assert.Throws<InvalidOperationException>(() => renderer.RenderEntrance(origin, kind, 42, random, true));
        Assert.Equal(before, Hash(tiles));
        Assert.Equal(new RandomAdapter(6789).Next(), random.Next());
    }

    [Fact]
    public void Entrance_platform_precedes_later_candidates_without_discarding_source_duplicates()
    {
        var tiles = new WorldTileStore(new WorldDimensions(100, 100));
        var entrancePlatform = new DungeonPoint1458(40, 40);
        DungeonComponent1458[] components = [new(DungeonComponentKind1458.Hall, entrancePlatform,
            new(40, 50), new(35, 35, 45, 55), 42) { HallDirection = new(0, 1) }];
        var graph = new DungeonGraph1458(components, new(60, 40), 41, 7, entrancePlatform: entrancePlatform);
        var candidates = DungeonFeatureCandidates1458.Collect(tiles, graph);
        var platforms = candidates.Platforms;
        var doors = candidates.Doors;
        Assert.Equal([entrancePlatform, entrancePlatform, new DungeonPoint1458(40, 50)], platforms.Select(p => p.Position));
        Assert.Empty(doors);
    }

    private static WorldTileStore Fixture(int f, ushort wall)
    {
        var tiles = new WorldTileStore(new WorldDimensions(1000, 600));
        for (int x = 0; x < 1000; x++)
        for (int y = 0; y < 600; y++)
        {
            bool active = y >= 145;
            ushort type = 1, background = 40;
            if (f == 2)
            {
                active = (x + y) % 3 == 0;
                background = (ushort)((x + y) % 4 == 0 ? wall : (x + y) % 4 == 1 ? 8 : 40);
                type = (ushort)((x + y) % 2 == 0 ? 41 : 481);
            }
            if (f == 0) { background = 0; active = false; }
            if (f == 5 && ((x >= 245 && x <= 255) || (x >= 745 && x <= 755))) { background = wall; active = false; }
            tiles.Set(x, y, new WorldTile
            {
                Type = type, Wall = background, FrameX = 18, FrameY = 36, TileColor = 3, WallColor = 4,
                LiquidAmount = 100, LiquidKind = (WorldLiquidKind)((x + y) % 4), Shape = (byte)((x + y) % 6),
                Flags = (active ? WorldTileFlags.Active : 0) | WorldTileFlags.WireRed |
                    WorldTileFlags.InvisibleWall | WorldTileFlags.FullbrightBlock | (f == 4 ? WorldTileFlags.Inactive : 0)
            });
        }
        return tiles;
    }
    private static int Int(string value) => int.Parse(value, CultureInfo.InvariantCulture);
    private static DungeonPoint1458 Point(string text) { string[] xy = text.Split(','); return new(Int(xy[0]), Int(xy[1])); }
    private static string Hash(WorldTileStore tiles)
    {
        var ordered = new WorldTile[600000];
        for (int x = 0; x < 1000; x++)
        for (int y = 0; y < 600; y++) ordered[x * 600 + y] = tiles.Get(x, y);
        return Convert.ToHexString(SHA256.HashData(MemoryMarshal.AsBytes(ordered.AsSpan())));
    }
