    [Theory]
    [MemberData(nameof(Platforms))]
    public void Platforms_match_clearance_rejection_duplicates_and_shelf_rng(string reference)
    {
        var f = reference.Split('|'); int fixture = Int(f[0]), palette = Int(f[1]);
        ushort brick = new ushort[] { 41, 43, 44 }[palette];
        var tiles = new WorldTileStore(new WorldDimensions(240, 240));
        for (int x = 0; x < 240; x++)
        for (int y = 0; y < 240; y++)
        {
            int half = fixture is 5 or 6 ? 15 : 5;
            bool active = x <= 100 - half || x >= 100 + half || y < 85 || y > 115;
            ushort type = fixture == 4 ? (ushort)1 : brick;
            if (fixture == 1 && x == 100 && y == 98) { active = true; type = 19; }
            if (fixture == 2 && x == 100 && y == 98) active = true;
            tiles.Set(x, y, new WorldTile
            {
                Type = type, Wall = 7, Flags = (active ? WorldTileFlags.Active : 0) | WorldTileFlags.WireRed | WorldTileFlags.FullbrightBlock,
                TileColor = 3, WallColor = 4, FrameX = 18, FrameY = type == 19 ? (short)108 : (short)36
            });
        }
        var p = new DungeonPlatformCandidate1458(new(100, 100))
        {
            HeightFluff = fixture == 6 ? 0 : 5, ForcePlacement = fixture == 6,
            PotsChance = fixture == 7 ? .25 : 0, BooksChance = fixture == 8 ? .75 : 0, PotionsChance = fixture == 9 ? .1 : 0
        };
        var random = new RandomAdapter(1458);
        new DungeonPlatforms1458(tiles, random, 60, 140, TestContext.Current.CancellationToken).Place(fixture == 3 ? [p, p] : [p], palette);
        Assert.Equal(f[2], HashCells(tiles));
        Assert.Equal(Int(f[3]), random.Next());
    }

    [Theory]
    [MemberData(nameof(Structures))]
    public void Pillars_wedges_and_mosaics_match_original_cells(string reference)
    {
        var f = reference.Split('|'); int fixture = Int(f[0]), palette = Int(f[1]);
        ushort brick = new ushort[] { 41, 43, 44 }[palette], wall = (ushort)(7 + palette);
        var tiles = new WorldTileStore(new WorldDimensions(240, 240));
        for (int x = 0; x < 240; x++)
        for (int y = 0; y < 240; y++)
            tiles.Set(x, y, new WorldTile
            {
                Type = 1, Wall = (ushort)((x + y) % 17 == 0 ? 91 : 40), FrameX = 18, FrameY = 36,
                TileColor = 3, WallColor = 4, LiquidAmount = 80, LiquidKind = WorldLiquidKind.Shimmer,
                Flags = WorldTileFlags.WireRed | WorldTileFlags.FullbrightBlock | ((y < 70 || y > 135) ? WorldTileFlags.Active : 0)
            });
        var random = new RandomAdapter(1458);
        if (fixture < 2) new DungeonMosaicWindows1458(tiles, 91, wall, 26).Place(120, 110, fixture + 1);
        else if (fixture < 6) new DungeonPillars1458(tiles, brick, random).Place(120, fixture == 5 ? 71 : 130, 3,
            fixture == 2 ? 16 : 0, fixture >= 4, fixture >= 3, fixture >= 3);
        else new DungeonPillars1458(tiles, brick, random).BottomWedge(120, 110, 5, fixture == 6);
        Assert.Equal(f[2], HashCells(tiles));
        Assert.Equal(Int(f[3]), random.Next());
    }
    private static string HashCells(WorldTileStore tiles)
    {
        var cells = new WorldTile[240 * 240];
        for (int x = 0; x < 240; x++)
        for (int y = 0; y < 240; y++) cells[x * 240 + y] = tiles.Get(x, y);
        return Convert.ToHexString(SHA256.HashData(MemoryMarshal.AsBytes(cells.AsSpan())));
    }
