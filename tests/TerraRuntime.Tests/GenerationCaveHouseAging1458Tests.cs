    public void Every_ordinary_room_aging_profile_matches_actual_original_all_cells_and_full_random(
        int kind, int profile, int seed, string expectedGrid, string expectedRandom, int expectedNext)
    {
        var workspace = new Workspace(80, 80);
        Assert.True(workspace.TrySetLayers(Surface(profile), 65));
        Populate((x, y, cell) =>
        {
            WorldTile tile = ConvertCell(cell);
            workspace.TileStore.Set(x, y, in tile);
        }, kind, profile);
        var random = new RandomAdapter(seed);
        CaveHousePlacement1458.AgeRoom(workspace, random, (CaveHouseType1458)kind, Room(profile));
        Assert.Equal(expectedGrid, Hash(workspace));
        Assert.Equal(expectedRandom, random.CapturePhysicalRandomHash());
        Assert.Equal(expectedNext, random.Next());
    }

    private static WorldTile ConvertCell(Cell cell) => new()
    {
        Type = cell.Type, Wall = cell.Wall, FrameX = cell.Fx, FrameY = cell.Fy,
        Shape = cell.Shape, TileColor = cell.TileColor, WallColor = cell.WallColor,
        LiquidAmount = cell.Liquid, LiquidKind = (WorldLiquidKind)cell.Kind,
        Flags = (cell.Active ? WorldTileFlags.Active : WorldTileFlags.None) |
            (cell.Actuated ? WorldTileFlags.Inactive : WorldTileFlags.None) |
            (cell.Actuator ? WorldTileFlags.Actuator : WorldTileFlags.None) |
            (cell.Wires ? WorldTileFlagMasks.Wires : WorldTileFlags.None) |
            (cell.Coatings ? WorldTileFlagMasks.Visibility | WorldTileFlagMasks.Fullbright : WorldTileFlags.None)
    };

    private static double Surface(int profile) => profile == 0 ? 40 : profile == 1 ? 20 : 30;
    private static CaveHouseRoom1458 Room(int profile) => new(30, 30, profile == 2 ? 7 : 14, profile == 2 ? 7 : 10);

    private readonly record struct Cell(ushort Type = 0, ushort Wall = 0, short Fx = 0, short Fy = 0,
        bool Active = false, byte Shape = 0, bool Actuated = false, bool Actuator = false,
        bool Wires = false, bool Coatings = false, byte TileColor = 0, byte WallColor = 0,
        byte Liquid = 0, byte Kind = 0);

    private static void Populate(Action<int, int, Cell> write, int kind, int profile)
    {
        ushort[] blocks = [30, 321, 396, 158, 190, 369, 357];
        ushort[] walls = [27, 149, 187, 42, 74, 181, 179];
        int width = profile == 2 ? 7 : 14, height = profile == 2 ? 7 : 10;
        for (int x = 26; x < 50; x++)
        for (int y = 26; y < 48; y++)
        {
            bool shell = x >= 30 && x < 30 + width && y >= 30 && y < 30 + height &&
                (x == 30 || x == 29 + width || y == 30 || y == 29 + height);
            bool inside = x > 30 && x < 29 + width && y > 30 && y < 29 + height;
            bool mixed = profile == 1 && inside && (x + y) % 4 == 0;
            ushort type = blocks[kind];
            ushort wall = (ushort)(shell || inside ? walls[kind] : (x + y) % 3 == 0 ? 1 : 0);
            bool active = shell || mixed;
            if (profile == 1 && inside && x % 5 == 0)
            {
                type = (ushort)(240 + y % 3);
                active = y % 2 == 0;
            }
            if (profile == 1 && inside && y % 3 == 0) wall = 21;
            write(x, y, new Cell(type, wall, (short)(profile == 1 ? 17 : 0), (short)(profile == 1 ? 23 : 0),
                active, (byte)(profile == 1 ? (x + y) % 6 : 0), profile == 1 && x % 3 == 0,
                profile == 1, profile == 1, profile == 1, (byte)(profile == 1 ? 5 : 0),
                (byte)(profile == 1 ? 7 : 0), (byte)(profile == 1 ? 23 : 0), (byte)(profile == 1 ? 2 : 0)));
        }
        // Framed replacement and clearing can reach adjacent objects. A torch on the edge
        // supplies a visible validator side effect without a parallel furniture owner.
        write(29, 33, new Cell(4, walls[kind], Active: true));
        for (int x = 26; x < 50; x++) write(x, 49, new Cell(1, Active: true));
    }

    private static string Hash(Workspace workspace)
    {
        var text = new StringBuilder();
        for (int x = 0; x < workspace.WidthTiles; x++)
        for (int y = 0; y < workspace.HeightTiles; y++)
        {
            WorldTile t = workspace.TileStore.Get(x, y);
            text.Append(t.IsActive ? 1 : 0).Append(',').Append(t.Type).Append(',').Append(t.Wall).Append(',')
                .Append(t.FrameX).Append(',').Append(t.FrameY).Append(',').Append(t.LiquidAmount).Append(',')
                .Append((byte)t.LiquidKind).Append(',').Append(t.TileColor).Append(',').Append(t.WallColor).Append(',')
                .Append(t.IsHalfBrick ? 1 : 0).Append(',').Append(t.Shape >= 2 ? t.Shape - 1 : 0).Append(',')
                .Append((t.Flags & WorldTileFlags.WireRed) != 0 ? 1 : 0).Append(',')
                .Append((t.Flags & WorldTileFlags.WireBlue) != 0 ? 1 : 0).Append(',')
                .Append((t.Flags & WorldTileFlags.WireGreen) != 0 ? 1 : 0).Append(',')
                .Append((t.Flags & WorldTileFlags.WireYellow) != 0 ? 1 : 0).Append(',')
                .Append((t.Flags & WorldTileFlags.Actuator) != 0 ? 1 : 0).Append(',').Append(t.IsActuated ? 1 : 0).Append(',')
                .Append((t.Flags & WorldTileFlags.InvisibleBlock) != 0 ? 1 : 0).Append(',')
                .Append((t.Flags & WorldTileFlags.InvisibleWall) != 0 ? 1 : 0).Append(',')
                .Append((t.Flags & WorldTileFlags.FullbrightBlock) != 0 ? 1 : 0).Append(',')
                .Append((t.Flags & WorldTileFlags.FullbrightWall) != 0 ? 1 : 0).Append(';');
        }
        return Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(text.ToString())));
    }

    private sealed class RandomAdapter(int seed) : IWorldGenerationVanillaRandom
    {
        private readonly VanillaUnifiedRandom1458 random = new(seed);
        public int Next() => random.Next();
        public int Next(int max) => random.Next(max);
        public int Next(int min, int max) => random.Next(min, max);
        public double NextDouble() => random.NextDouble();
        public void NextBytes(byte[] buffer) => random.NextBytes(buffer);
        public string CapturePhysicalRandomHash()
        {
            const BindingFlags flags = BindingFlags.Instance | BindingFlags.NonPublic;
            using var bytes = new MemoryStream();
            using var writer = new BinaryWriter(bytes);
            writer.Write((uint)typeof(VanillaUnifiedRandom1458).GetField("inext", flags)!.GetValue(random)!);
            foreach (int value in (int[])typeof(VanillaUnifiedRandom1458).GetField("seedArray", flags)!.GetValue(random)!) writer.Write(value);
            return Convert.ToHexString(SHA256.HashData(bytes.ToArray()));
        }
    }
