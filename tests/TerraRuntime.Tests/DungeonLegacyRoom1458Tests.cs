    [Theory]
    [InlineData(0, 42, 94, 53, 131, 89)]
    [InlineData(0, 1458, 109, 69, 130, 99)]
    [InlineData(0, 8675309, 107, 63, 147, 96)]
    [InlineData(4, 42, 10, 10, 12, 11)]
    [InlineData(4, 1458, 10, 10, 11, 14)]
    [InlineData(4, 8675309, 10, 10, 28, 11)]
    [InlineData(5, 42, 212, 138, 230, 170)]
    [InlineData(5, 1458, 227, 154, 230, 170)]
    [InlineData(5, 8675309, 225, 148, 230, 170)]
    public void Inner_bounds_match_official_metadata_including_world_edge_clamps(int fixture, int seed,
        int left, int top, int right, int bottom)
    {
        var room = DungeonLegacyRoom1458.Generate(Fixture(fixture), 41, 7, Origin(fixture), seed, false, TestContext.Current.CancellationToken);
        Assert.Equal(new DungeonBounds1458(left, top, right, bottom), room.InnerBounds);
    }

    // Official TerrariaServer 1.4.5.8 Linux binary:
    // SHA256 4B87890AC53D40F61DB5F928693A379ACF4CCBD8ED3B47EB32FB096F145DF034.
    // Independent LegacyDungeonRoom.GenerateRoom output: all normalized fields, x-major.
    public static IEnumerable<object[]> OfficialRooms()
    {
        foreach (string row in Reference.Split('\n', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries))
        {
            string[] fields = row.Split('|');
            yield return [int.Parse(fields[0], CultureInfo.InvariantCulture),
                int.Parse(fields[1], CultureInfo.InvariantCulture), int.Parse(fields[2], CultureInfo.InvariantCulture),
                fields[3], fields[4], fields[5]];
        }
    }

    [Theory]
    [MemberData(nameof(OfficialRooms))]
    public void Room_matches_official_full_cells_and_endpoints(int fixture, int palette, int seed,
        string hash, string start, string end)
    {
        WorldTileStore tiles = Fixture(fixture);
        ushort brick = palette == 0 ? (ushort)41 : palette == 1 ? (ushort)43 : (ushort)44;
        DungeonComponent1458 room = DungeonLegacyRoom1458.Generate(tiles, brick, (ushort)(7 + palette),
            Origin(fixture), seed, false, TestContext.Current.CancellationToken);
        Assert.Equal(hash, Hash(tiles));
        Assert.Equal(Point(start), room.Start);
        Assert.Equal(Point(end), room.End);
        Assert.Equal(DungeonComponentKind1458.Room, room.Kind);
        Assert.Equal(seed, room.RandomSeed);
        Assert.Equal(seed switch { 42 => 25, 1458 => 21, 8675309 => 26, _ => throw new InvalidOperationException() }, room.RoomStrength);
    }

    [Fact]
    public void Canceled_room_does_not_mutate_candidate()
    {
        WorldTileStore tiles = Fixture(0);
        string before = Hash(tiles);
        Assert.Throws<OperationCanceledException>(() =>
            DungeonLegacyRoom1458.Generate(tiles, 41, 7, Origin(0), 42, false, new CancellationToken(true)));
        Assert.Equal(before, Hash(tiles));
    }

    [Fact]
    public void Unsupported_palette_does_not_mutate_candidate()
    {
        WorldTileStore tiles = Fixture(0);
        string before = Hash(tiles);
        Assert.Throws<InvalidOperationException>(() =>
            DungeonLegacyRoom1458.Generate(tiles, 41, 8, Origin(0), 42, false, TestContext.Current.CancellationToken));
        Assert.Equal(before, Hash(tiles));
    }

    [Fact]
    public void Unknown_shell_wall_is_not_treated_as_replaceable()
    {
        WorldTileStore tiles = Fixture(0);
        for (int x = 0; x < 240; x++)
        for (int y = 0; y < 180; y++)
        {
            WorldTile tile = tiles.Get(x, y);
            tile.Wall = ushort.MaxValue;
            tiles.Set(x, y, tile);
        }
        Assert.Throws<InvalidOperationException>(() =>
            DungeonLegacyRoom1458.Generate(tiles, 41, 7, Origin(0), 42, false, TestContext.Current.CancellationToken));
    }

    private static DungeonPoint1458 Origin(int fixture) =>
        fixture == 4 ? new(1, 5) : fixture == 5 ? new(238, 175) : new(120, 90);

    private static DungeonPoint1458 Point(string text)
    {
        string[] values = text.Split(',');
        return new((int)double.Parse(values[0], CultureInfo.InvariantCulture),
            (int)double.Parse(values[1], CultureInfo.InvariantCulture));
    }

    private static WorldTileStore Fixture(int fixture)
    {
        var tiles = new WorldTileStore(new WorldDimensions(240, 180));
        for (int x = 0; x < 240; x++)
        for (int y = 0; y < 180; y++)
        {
            WorldTileFlags flags = WorldTileFlags.WireRed;
            if (fixture != 3 || (x + y) % 3 != 0) flags |= WorldTileFlags.Active;
            if (fixture == 6) flags |= WorldTileFlagMasks.Actuation | WorldTileFlagMasks.Visibility | WorldTileFlagMasks.Fullbright;
            tiles.Set(x, y, new WorldTile
            {
                Type = fixture == 2 ? (ushort)59 : (ushort)1,
                Wall = fixture == 1 ? (ushort)(x % 13 < 3 ? 350 : x % 13 < 7 ? 7 : 8) : (ushort)40,
                FrameX = 18, FrameY = 36, TileColor = 3, WallColor = 4,
                LiquidAmount = 17, LiquidKind = WorldLiquidKind.Lava,
                Shape = fixture == 6 ? (byte)3 : (byte)0, Flags = flags
            });
        }
        return tiles;
    }

    private static string Hash(WorldTileStore tiles)
    {
        var cells = new WorldTile[240 * 180];
        for (int x = 0; x < 240; x++)
        for (int y = 0; y < 180; y++)
            cells[x * 180 + y] = tiles.Get(x, y);
        return Convert.ToHexString(SHA256.HashData(MemoryMarshal.AsBytes(cells.AsSpan())));
    }

