    public static IEnumerable<object[]> BuildingsAndPlatforms() => Reference.Split('\n', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries).Select(row => new object[] { row });

    [Theory]
    [MemberData(nameof(BuildingsAndPlatforms))]
    public void Building_platforms_and_shelf_objects_match_original_tiles_and_rng(string reference)
    {
        string[] f = reference.Split('|');
        int fixture = Int(f[1]), palette = Int(f[2]), seed = Int(f[3]);
        bool right = bool.Parse(f[4]);
        ushort brick = palette == 0 ? (ushort)41 : palette == 1 ? (ushort)43 : (ushort)44;
        var tiles = Fixture(fixture, (ushort)(7 + palette));
        var random = new RandomAdapter(6789);
        var builder = new DungeonSurfaceBuildings1458(tiles, brick, (ushort)(481 + palette), (ushort)(7 + palette), 150.25, random, TestContext.Current.CancellationToken);
        var origin = new DungeonPoint1458(right ? 750 : 250, 180);
        var building = f[0] == "Dome" ? builder.GenerateDome(origin, seed, !right) : builder.GenerateTower(origin, seed, !right);
        var candidates = building.Platforms.Select(p => new DungeonPlatformCandidate1458(p.Position)
        {
            HeightFluff = p.HeightFluff, ForcePlacement = p.ForcePlacement,
            PotsChance = p.PotsChance, BooksChance = p.BooksChance, PotionsChance = p.PotionsChance, NoWaterbolt = p.NoWaterbolt
        }).ToArray();
        new DungeonPlatforms1458(tiles, random, 150.25, 220, TestContext.Current.CancellationToken).Place(candidates, palette);
        Assert.Equal(f[5], Hash(tiles));
        Assert.Equal(Int(f[6]), random.Next());
    }
