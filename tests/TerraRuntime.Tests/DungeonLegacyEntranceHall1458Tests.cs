    // Independent official LegacyEntranceDungeonHall.GenerateHall, normalized full cells + shared RNG.
    // TerrariaServer 1.4.5.8 Linux SHA256:
    // 4B87890AC53D40F61DB5F928693A379ACF4CCBD8ED3B47EB32FB096F145DF034.
    public static IEnumerable<object[]> OfficialEntrances()
    {
        foreach (string row in Reference.Split('\n', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries))
        {
            string[] f = row.Split('|');
            yield return [int.Parse(f[0], CultureInfo.InvariantCulture), int.Parse(f[1], CultureInfo.InvariantCulture),
                int.Parse(f[2], CultureInfo.InvariantCulture), f[3], f[4], bool.Parse(f[6]),
                int.Parse(f[7].AsSpan(5), CultureInfo.InvariantCulture)];
        }
    }

    [Theory]
    [MemberData(nameof(OfficialEntrances))]
    public void Entrance_matches_official_cells_cursor_surface_and_world_rng(int fixture, int palette, int seed,
        string hash, string end, bool reached, int next)
    {
        WorldTileStore tiles = Fixture(fixture);
        ushort brick = palette == 0 ? (ushort)41 : palette == 1 ? (ushort)43 : (ushort)44;
        var random = new RandomAdapter(6789);
        var result = new DungeonLegacyEntranceHall1458(tiles, brick, (ushort)(481 + palette),
            (ushort)(7 + palette), 150, 25, 35, 10, random, TestContext.Current.CancellationToken)
            .Generate(Origin(fixture), fixture == 3 ? 400 : fixture == 4 ? 600 : 250, seed, fixture is 3 or 4);
        Assert.Equal(hash, Hash(tiles));
        Assert.Equal(Point(end), result.Cursor);
        Assert.Equal(reached, result.ReachedSurface);
        Assert.Equal(next, random.Next());
        Assert.Equal(Origin(fixture), result.Component.Start);
        Assert.Equal(result.Cursor, result.Component.End);
        Assert.Equal(DungeonComponentKind1458.EntranceHall, result.Component.Kind);
        Assert.Equal(seed, result.Component.RandomSeed);
    }

    [Theory]
    [InlineData(true)] [InlineData(false)]
    public void Cancellation_or_unsupported_palette_rejects_before_mutation(bool cancelled)
    {
        WorldTileStore tiles = Fixture(0);
        string before = Hash(tiles);
        var random = new RandomAdapter(6789);
        var generator = new DungeonLegacyEntranceHall1458(tiles, 41, 481, cancelled ? (ushort)7 : (ushort)8,
            150, 25, 35, 10, random, new CancellationToken(cancelled));
        if (cancelled) Assert.Throws<OperationCanceledException>(() => generator.Generate(Origin(0), 250, 42, false));
        else Assert.Throws<InvalidOperationException>(() => generator.Generate(Origin(0), 250, 42, false));
        Assert.Equal(before, Hash(tiles));
        Assert.Equal(new RandomAdapter(6789).Next(), random.Next());
    }

    [Theory]
    [InlineData(24,10,0,-1)] [InlineData(35,10,0,-1)]
    [InlineData(25,9,0,-1)] [InlineData(25,20,0,-1)]
    [InlineData(25,10,1,-1)] [InlineData(25,10,0,0)]
    public void Air_opening_does_not_admit_unverified_runner_parameters(double strength, int steps, double vx, double vy)
    {
        WorldTileStore tiles = Fixture(0);
        var random = new RandomAdapter(6789);
        string before = Hash(tiles);
        Assert.Throws<ArgumentOutOfRangeException>(() =>
            new SmallTerrainRunner1458(tiles, random, 150, default, TestContext.Current.CancellationToken)
                .Run(300, 130, strength, steps, SmallTerrainRunner1458.AirCavity, speedX: vx, speedY: vy));
        Assert.Equal(before, Hash(tiles));
        Assert.Equal(new RandomAdapter(6789).Next(), random.Next());
    }

    private static DungeonPoint1458 Origin(int fixture) =>
        new(fixture == 3 ? 450 : fixture == 4 ? 550 : fixture == 8 ? 34 : 250,
            fixture is 1 or 6 ? 145 : fixture == 5 ? 40 : fixture == 9 ? 160 : 250);

    private static DungeonPoint1458 Point(string text)
    {
        string[] values = text.Split(',');
        return new((int)double.Parse(values[0], CultureInfo.InvariantCulture),
            (int)double.Parse(values[1], CultureInfo.InvariantCulture));
    }

    private static WorldTileStore Fixture(int fixture)
    {
        var tiles = new WorldTileStore(new WorldDimensions(1000, 600));
        ushort[] openingTypes = [1, 53, 3, 21], protectedTypes = [41, 677, 481];
        for (int x = 0; x < 1000; x++)
        for (int y = 0; y < 600; y++)
        {
            bool air = fixture == 1 && y < 150;
            WorldTileFlags flags = WorldTileFlags.WireRed;
            if (!air) flags |= WorldTileFlags.Active;
            if (fixture == 7) flags |= WorldTileFlagMasks.Actuation | WorldTileFlagMasks.Visibility | WorldTileFlagMasks.Fullbright;
            tiles.Set(x, y, new WorldTile
            {
                Type = fixture == 6 ? openingTypes[(x + y) % 4] : fixture == 7 ? protectedTypes[(x + y) % 3] : (ushort)1,
                Wall = air || (fixture == 6 && y < 150) ? (ushort)0 : fixture is 2 or 7 ? (ushort)7 : (ushort)40,
                FrameX = 18, FrameY = 36, TileColor = 3, WallColor = 4,
                LiquidAmount = 17, LiquidKind = WorldLiquidKind.Lava,
                Shape = fixture == 7 ? (byte)3 : (byte)0, Flags = flags
            });
        }
        return tiles;
    }

    private static string Hash(WorldTileStore tiles)
    {
        var cells = new WorldTile[1000 * 600];
        for (int x = 0; x < 1000; x++)
        for (int y = 0; y < 600; y++)
            cells[x * 600 + y] = tiles.Get(x, y);
        return Convert.ToHexString(SHA256.HashData(MemoryMarshal.AsBytes(cells.AsSpan())));
    }

    private sealed class RandomAdapter(int seed) : IWorldGenerationVanillaRandom
    {
        private readonly VanillaUnifiedRandom1458 random = new(seed);
        public int Next() => random.Next();
        public int Next(int max) => random.Next(max);
        public int Next(int min, int max) => random.Next(min, max);
        public double NextDouble() => random.NextDouble();
        public void NextBytes(byte[] bytes) => random.NextBytes(bytes);
    }

