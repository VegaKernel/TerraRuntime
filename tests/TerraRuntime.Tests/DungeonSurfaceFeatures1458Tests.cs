    // Independent full normalized tile arrays and next shared RNG; inputs are separate from expected output.
    public static IEnumerable<object[]> Cases => Reference.Split('\n', StringSplitOptions.RemoveEmptyEntries)
        .Select(line => line.Trim().Split('|')).Select(p => new object[]
        { int.Parse(p[0]), int.Parse(p[1]), int.Parse(p[2]), int.Parse(p[3]), p[4], int.Parse(p[5]) });

    [Theory, MemberData(nameof(Cases))]
    public void Spikes_walls_and_continuation_match_original(int mode, int fixture, int palette, int seed, string expected, int next)
    {
        var tiles = DungeonSurfaceFeatureFixture1458.Tiles(fixture, palette);
        var random = new RandomAdapter(seed);
        if (mode != 1) new DungeonSpikes1458(tiles, random, CancellationToken.None).Place(DungeonSurfaceFeatureFixture1458.Bounds,
            (ushort)(7 + palette), (ushort)(481 + palette), 60, DungeonSurfaceFeatureFixture1458.Entrance(fixture));
        if (mode != 0) new DungeonWallVariants1458(tiles, random, CancellationToken.None).Apply(DungeonSurfaceFeatureFixture1458.Bounds,
            (ushort)(7 + palette), DungeonSurfaceFeatureFixture1458.Variants(palette), 60);
        Assert.Equal(expected, Hash(tiles));
        Assert.Equal(next, random.Next());
    }

    [Fact]
    public void Large_connected_air_region_is_iterative_and_keeps_all_non_wall_metadata()
    {
        var tiles = new WorldTileStore(new WorldDimensions(512, 512));
        var input = new WorldTile { Wall = 7, Flags = WorldTileFlags.WireRed, LiquidAmount = 99, LiquidKind = WorldLiquidKind.Lava, TileColor = 3, WallColor = 4 };
        tiles.Tiles.Fill(input);
        new DungeonWallVariants1458(tiles, new RandomAdapter(42), CancellationToken.None).Spread(200, 200, 7, 94);
        for (int x = 0; x < 512; x++)
        for (int y = 0; y < 512; y++)
        {
            WorldTile expected = input;
            if (x >= 5 && x < 507 && y >= 5 && y < 507) expected.Wall = 94;
            Assert.Equal(expected, tiles.Get(x, y));
        }
    }

    [Theory]
    [InlineData(0, false, false)]
    [InlineData(1, false, true)]
    [InlineData(0, true, true)]
    public void Full_solid_boundary_stops_spread_but_half_brick_or_actuation_does_not(byte shape, bool actuated, bool crosses)
    {
        var tiles = new WorldTileStore(new WorldDimensions(80, 80));
        tiles.Tiles.Fill(new WorldTile { Wall = 7 });
        for (int y = 0; y < 80; y++) tiles.Set(40, y, new WorldTile
        { Wall = 7, Type = 41, Flags = WorldTileFlags.Active | (actuated ? WorldTileFlags.Inactive : 0), Shape = shape });
        new DungeonWallVariants1458(tiles, new RandomAdapter(42), CancellationToken.None).Spread(20, 40, 7, 94);
        Assert.Equal((ushort)94, tiles.Get(40, 40).Wall); // Source recolors even the full solid border.
        Assert.Equal(crosses ? (ushort)94 : (ushort)7, tiles.Get(41, 40).Wall);
    }

    [Fact]
    public void Zero_source_spike_target_does_not_invent_one_or_consume_random()
    {
        var random = new RandomAdapter(42);
        Assert.Equal(0, new DungeonSpikes1458(new(new WorldDimensions(50, 100)), random, CancellationToken.None)
            .Place(new(10, 10, 40, 70), 7, 481, 0));
        Assert.Equal(new RandomAdapter(42).Next(), random.Next());
    }

    [Fact]
    public void Open_world_edges_cannot_make_spike_scans_leave_workspace()
    {
        var tiles = new WorldTileStore(new WorldDimensions(200, 120));
        tiles.Tiles.Fill(new WorldTile { Wall = 7 });
        string before = Hash(tiles);
        new DungeonSpikes1458(tiles, new RandomAdapter(42), CancellationToken.None).Place(new(10, 30, 180, 100), 7, 481, 10);
        Assert.Equal(before, Hash(tiles));
    }

    [Fact]
    public void Cancellation_and_unknown_palettes_are_fail_closed()
    {
        var tiles = DungeonSurfaceFeatureFixture1458.Tiles(0, 0);
        var bounds = DungeonSurfaceFeatureFixture1458.Bounds;
        string before = Hash(tiles);
        Assert.Throws<OperationCanceledException>(() => new DungeonSpikes1458(tiles, new RandomAdapter(42), new CancellationToken(true)).Place(bounds, 7, 481, 60));
        Assert.Throws<OperationCanceledException>(() => new DungeonWallVariants1458(tiles, new RandomAdapter(42), new CancellationToken(true)).Apply(bounds, 7, [7, 94, 95], 60));
        Assert.Throws<InvalidOperationException>(() => new DungeonSpikes1458(tiles, new RandomAdapter(42), CancellationToken.None).Place(bounds, 40, 481, 60));
        Assert.Throws<InvalidOperationException>(() => new DungeonWallVariants1458(tiles, new RandomAdapter(42), CancellationToken.None).Apply(bounds, 8, [8, 96, 97], 60));
        Assert.Equal(before, Hash(tiles));
    }

