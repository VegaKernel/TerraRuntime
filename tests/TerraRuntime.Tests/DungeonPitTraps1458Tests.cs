    // Independent original 1.4.5.8 executable SHA256:
    // 4B87890AC53D40F61DB5F928693A379ACF4CCBD8ED3B47EB32FB096F145DF034.
    public static IEnumerable<object[]> Cases => Reference.Split('\n', StringSplitOptions.RemoveEmptyEntries)
        .Select(line => line.Trim().Split('|')).Select(p => new object[]
        { int.Parse(p[0]), int.Parse(p[1]), int.Parse(p[2]), p[3], int.Parse(p[4]), p[5] });

    [Theory, MemberData(nameof(Cases))]
    public void Ordinary_early_feature_matches_all_cells_bounds_flooding_and_shared_random(
        int fixture, int palette, int seed, string expected, int next, string expectedPits)
    {
        var tiles = DungeonSurfaceFeatureFixture1458.PitTiles(fixture, palette);
        var random = new RandomAdapter(seed);
        var pits = new DungeonPitTraps1458(tiles, random, CancellationToken.None)
            .Place(new(60, 180, 550, 340), new ushort[] { 41, 43, 44 }[palette],
                (ushort)(7 + palette), (ushort)(481 + palette), 60, 160);
        Assert.Equal(expected, Convert.ToHexString(SHA256.HashData(MemoryMarshal.AsBytes(tiles.Tiles))));
        Assert.Equal(next, random.Next());
        Assert.Equal(expectedPits, string.Join(';', pits.Select(p =>
            $"{p.Bounds.Left},{p.Bounds.Top},{p.Bounds.Right},{p.Bounds.Bottom},{p.Flooded}")));
    }

    [Fact]
    public void Cancellation_does_not_consume_random_or_edit_tiles()
    {
        var tiles = DungeonSurfaceFeatureFixture1458.PitTiles(0, 0);
        string before = DungeonSurfaceBuildings1458Tests.Hash(tiles);
        var random = new RandomAdapter(42);
        Assert.Throws<OperationCanceledException>(() => new DungeonPitTraps1458(tiles, random, new(true))
            .Place(new(60, 180, 550, 340), 41, 7, 481, 60, 160));
        Assert.Equal(before, DungeonSurfaceBuildings1458Tests.Hash(tiles));
        Assert.Equal(new RandomAdapter(42).Next(), random.Next());
    }

    [Theory]
    [InlineData(20, 30, true)]
    [InlineData(39, 49, true)]
    [InlineData(40, 49, false)]
    [InlineData(39, 50, false)]
    [InlineData(19, 30, false)]
    public void Feature_protection_uses_exclusive_source_rectangle_edges(int x, int y, bool expected) =>
        Assert.Equal(expected, DungeonPitTraps1458.Contains([new(new(20, 30, 40, 50), true)], x, y));

