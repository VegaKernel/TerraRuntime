    public static IEnumerable<object[]> OfficialRoutes() =>
        Reference.Split('\n', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries).Select(row => new object[] { row });

    [Theory]
    [MemberData(nameof(OfficialRoutes))]
    public void Production_route_matches_full_cells_each_step_bounds_cursor_countdown_platforms_and_rng(string reference)
    {
        string[] f = reference.Split('|');
        int fixture = Int(f[0]), palette = Int(f[1]), seed = Int(f[2]);
        var tiles = Fixture(fixture);
        ushort brick = palette == 0 ? (ushort)41 : palette == 1 ? (ushort)43 : (ushort)44;
        var random = new RandomAdapter(seed);
        var endpoints = Endpoints(fixture);
        var route = new DungeonEntranceRoute1458(endpoints.Start, endpoints.Target);
        var platforms = new List<DungeonHallPlatform1458>();
        var renderer = new DungeonGraphGenerator1458.Renderer(tiles, brick, (ushort)(481 + palette), (ushort)(7 + palette),
            200, 300, 400, 1, 998, 25, 20, 35, 10, TestContext.Current.CancellationToken);
        var sequence = new List<string>();
        var components = new List<DungeonComponent1458>();
        do
        {
            var segment = route.TakeNext(random);
            DungeonComponent1458 component = renderer.RenderPrecalculatedEntranceSegment(segment, random, platforms, out var cursor);
            components.Add(component);
            DungeonBounds1458 b = component.Bounds;
            sequence.Add(FormattableString.Invariant(
                $"{route.Remaining}:{route.Current.X:R},{route.Current.Y:R}:{cursor.X},{cursor.Y}:{b.Left},{b.Top},{b.Right},{b.Bottom}"));
        } while (!route.Complete && sequence.Count < 99);
        Assert.True(route.Complete);
        DungeonSamplingBoundsReference1458.AssertMatches($"Route|{fixture}|{palette}|{seed}", tiles.Dimensions,
            new(500, 450), components);
        Assert.Equal(f[3], HashTiles(tiles));
        Assert.Equal(Int(f[4]), random.Next());
        Assert.Equal(f[5], HashText(string.Join(';', sequence)));
        Assert.Equal(f[6], HashText(string.Join(';', platforms.Select(p =>
            FormattableString.Invariant($"{p.Position.X},{p.Position.Y},{p.InAHallway},{p.PlacePotsChance}")))));
    }

    [Fact]
    public void Invalid_route_does_not_admit_zero_or_nonfinite_endpoints()
    {
        Assert.Throws<InvalidOperationException>(() => new DungeonEntranceRoute1458(new(10, 10), new(10, 10)));
        Assert.Throws<InvalidOperationException>(() => new DungeonEntranceRoute1458(default, new(10, 10)));
        Assert.Throws<InvalidOperationException>(() => new DungeonEntranceRoute1458(new(double.NaN, 10), new(20, 20)));
        Assert.Throws<InvalidOperationException>(() => new DungeonEntranceRoute1458(new(10, 10), new(double.PositiveInfinity, 20)));
    }

    [Fact]
    public void Completed_route_does_not_consume_another_seed()
    {
        var random = new RandomAdapter(42);
        var route = new DungeonEntranceRoute1458(new(50, 50), new(50, 50.5));
        route.TakeNext(random);
        Assert.True(route.Complete);
        var expected = new RandomAdapter(42);
        _ = expected.Next(10, 30); _ = expected.Next();
        Assert.Throws<InvalidOperationException>(() => route.TakeNext(random));
        Assert.Equal(expected.Next(), random.Next());
    }

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public void Invalid_or_cancelled_segment_does_not_touch_candidate_platforms_or_shared_rng(bool cancel)
    {
        var tiles = Fixture(0);
        string before = HashTiles(tiles);
        var random = new RandomAdapter(42);
        var platforms = new List<DungeonHallPlatform1458> { new(new(50, 50), true, .25) };
        var hall = new DungeonLegacyEntranceHall1458(tiles, 41, 481, 7, 200, 25, 35, 10, random, new CancellationToken(cancel));
        var segment = new DungeonEntranceSegment1458(new(250, 250), new(double.NaN, 100), 5, 42);
        if (cancel) Assert.Throws<OperationCanceledException>(() => hall.GeneratePrecalculated(segment, platforms));
        else Assert.Throws<InvalidOperationException>(() => hall.GeneratePrecalculated(segment, platforms));
        Assert.Equal(before, HashTiles(tiles));
        Assert.Single(platforms);
        Assert.Equal(new RandomAdapter(42).Next(), random.Next());
    }

    [Fact]
    public void Connection_platforms_precede_building_and_room_candidates()
    {
        var tiles = new WorldTileStore(new WorldDimensions(100, 100));
        DungeonHallPlatform1458[] connection = [new(new(40, 40), true, .25), new(new(40, 40), true, .25)];
        var graph = new DungeonGraph1458([], new(60, 40), 41, 7, entrancePlatform: new(40, 50), entranceHallPlatforms: connection);
        var candidates = DungeonFeatureCandidates1458.Collect(tiles, graph);
        var platforms = candidates.Platforms;
        Assert.Equal([new DungeonPoint1458(40, 40), new DungeonPoint1458(40, 40), new DungeonPoint1458(40, 50)], platforms.Select(p => p.Position));
        Assert.Equal(.25, platforms[0].PotsChance);
        Assert.Equal(.25, platforms[1].PotsChance);
        Assert.Equal(2, graph.EntranceHallPlatforms.Count); // Source records remain ordered, not silently deduplicated.
    }

    private static (DungeonPosition1458 Start, DungeonPosition1458 Target) Endpoints(int fixture) => fixture switch
    {
        0 => (new(250, 300), new(310, 150)),
        1 => (new(250.25, 320.75), new(320.125, 170.5)),
        2 => (new(750, 250), new(680, 160)),
        3 => (new(200, 160), new(350, 160)),
        4 => (new(270, 160), new(270.25, 160.75)),
        _ => (new(34, 160), new(90, 160))
    };
    private static WorldTileStore Fixture(int fixture)
    {
        var tiles = new WorldTileStore(new WorldDimensions(1000, 600));
        for (int x = 0; x < 1000; x++)
        for (int y = 0; y < 600; y++)
            tiles.Set(x, y, new WorldTile
            {
                Type = (ushort)((x + y) % 3 == 0 ? 41 : 1),
                Wall = (ushort)(fixture % 2 == 0 ? 40 : (x + y) % 4 == 0 ? 7 : (x + y) % 4 == 1 ? 350 : 0),
                FrameX = 18, FrameY = 36, TileColor = 3, WallColor = 4, LiquidAmount = 100,
                LiquidKind = (WorldLiquidKind)((x + y) % 4), Shape = (byte)((x + y) % 6),
                Flags = ((x + y) % 5 == 0 ? 0 : WorldTileFlags.Active) | WorldTileFlags.WireRed |
                    WorldTileFlags.InvisibleWall | WorldTileFlags.FullbrightBlock | ((x + y) % 7 == 0 ? WorldTileFlags.Inactive : 0)
            });
        return tiles;
    }
    private static int Int(string value) => int.Parse(value, CultureInfo.InvariantCulture);
    private static string HashText(string text) => Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(text)));
    private static string HashTiles(WorldTileStore tiles)
    {
        var cells = new WorldTile[600000];
        for (int x = 0; x < 1000; x++)
        for (int y = 0; y < 600; y++) cells[x * 600 + y] = tiles.Get(x, y);
        return Convert.ToHexString(SHA256.HashData(MemoryMarshal.AsBytes(cells.AsSpan())));
    }
