{
    // Original TerrariaServer 1.4.5.8 full-cell / shared-RNG outputs, with a generated pit's
    // actual CanGenerateFeatureAt gate. No source method bodies or candidate-produced goldens.
    public static IEnumerable<object[]> Cases => Reference.Split('\n', StringSplitOptions.RemoveEmptyEntries)
        .Select(row => new object[] { row.Trim() });

    [Theory, MemberData(nameof(Cases))]
    public void Protected_pit_gates_consumers_but_not_wall_variants(string reference)
    {
        string[] p = reference.Split('|');
        string kind = p[0];
        int mode = int.Parse(p[1]), fixture = int.Parse(p[2]), palette = int.Parse(p[3]), seed = int.Parse(p[4]);
        var workspace = kind == "furniture" ? DungeonSurfaceFeatureFixture1458.FurnitureTiles(fixture, palette) : null;
        var tiles = workspace?.TileStore ?? (kind == "spikes"
            ? DungeonSurfaceFeatureFixture1458.Tiles(fixture, palette)
            : DungeonSurfaceFeatureFixture1458.BookshelfTiles(fixture, palette));
        var random = new DungeonSurfaceBuildings1458Tests.RandomAdapter(seed);
        var cancellation = TestContext.Current.CancellationToken;
        var bounds = kind == "furniture" ? new DungeonBounds1458(40, 60, 350, 540) : DungeonSurfaceFeatureFixture1458.Bounds;
        DungeonPitTraps1458.Pit[] pits = [new(new(75, 90, 300, tiles.Dimensions.HeightTiles - 70), true)];
        int[] variants = DungeonSurfaceFeatureFixture1458.Variants(palette);
        var entrance = DungeonSurfaceFeatureFixture1458.Entrance(fixture);
        switch (kind)
        {
            case "bookshelves":
                new DungeonBookshelves1458(tiles, random, 60, 140, cancellation, pits)
                    .Place(bounds, variants, DungeonDecorationProfile1458.Default, entrance);
                break;
            case "lights":
                new DungeonLights1458(tiles, random, cancellation, pits)
                    .Place(bounds, variants, palette, DungeonDecorationProfile1458.Default, entrance);
                break;
            case "banners":
                new DungeonBanners1458(tiles, random, cancellation, pits).Place(bounds, variants);
                break;
            case "furniture":
                new DungeonFurniture1458(workspace!, random, cancellation, pits).Place(bounds, (ushort)(7 + palette), 60);
                break;
            case "spikes":
                if (mode != 1) new DungeonSpikes1458(tiles, random, cancellation, pits)
                    .Place(bounds, (ushort)(7 + palette), (ushort)(481 + palette), 60, entrance);
                if (mode != 0) new DungeonWallVariants1458(tiles, random, cancellation)
                    .Apply(bounds, (ushort)(7 + palette), variants, 60);
                break;
            default: throw new InvalidOperationException("Unknown fixture.");
        }
        Assert.Equal(p[5], DungeonSurfaceBuildings1458Tests.Hash(tiles));
        Assert.Equal(int.Parse(p[6]), random.Next());
    }

