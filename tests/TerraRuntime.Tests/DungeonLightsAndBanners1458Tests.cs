    // Original TerrariaServer 1.4.5.8 SHA256 4B87890AC53D40F61DB5F928693A379ACF4CCBD8ED3B47EB32FB096F145DF034.
    public static IEnumerable<object[]> Cases => Reference.Split('\n', StringSplitOptions.RemoveEmptyEntries)
        .Select(line => new object[] { line.Trim() });

    [Theory, MemberData(nameof(Cases))]
    public void Full_feature_tiles_and_next_random_match_original(string row)
    {
        string[] p = row.Split('|');
        int fixture = int.Parse(p[1]), palette = int.Parse(p[2]), seed = int.Parse(p[3]);
        var tiles = DungeonSurfaceFeatureFixture1458.BookshelfTiles(fixture, palette);
        var random = new RandomAdapter(seed);
        if (p[0] == "lights")
            new DungeonLights1458(tiles, random, CancellationToken.None).Place(DungeonSurfaceFeatureFixture1458.Bounds,
                DungeonSurfaceFeatureFixture1458.Variants(palette), palette, DungeonDecorationProfile1458.Default,
                DungeonSurfaceFeatureFixture1458.Entrance(fixture));
        else
            new DungeonBanners1458(tiles, random, CancellationToken.None).Place(DungeonSurfaceFeatureFixture1458.Bounds,
                DungeonSurfaceFeatureFixture1458.Variants(palette));
        Assert.Equal(p[4], Convert.ToHexString(SHA256.HashData(MemoryMarshal.AsBytes(tiles.Tiles))));
        Assert.Equal(int.Parse(p[5]), random.Next());
    }

