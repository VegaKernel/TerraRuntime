    // Includes Item.Prefix(-1), all depth branches and two successive chests sharing first-key/rune state.
    public static IEnumerable<object[]> Cases()
    {
        string[] rows = Reference.Split('\n', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries);
        for (int i = 0; i < rows.Length; i += 2) yield return new object[] { rows[i], rows[i + 1] };
