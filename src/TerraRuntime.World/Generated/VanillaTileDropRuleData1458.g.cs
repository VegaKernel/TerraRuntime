    public static VanillaTileDropRule Get(TileTypeId type)
    {
        int index = type.Value;
        VanillaTileDropRuleKind kind = (VanillaTileDropRuleKind)Kinds[index];
        return new VanillaTileDropRule(
            kind,
            PrimaryItems[index] == 0 ? default : new ItemTypeId(PrimaryItems[index]),
            PrimaryStacks[index],
            SecondaryItems[index] == 0 ? default : new ItemTypeId(SecondaryItems[index]),
            SecondaryStacks[index],
            (Flags[index] & 1) != 0);
    }
